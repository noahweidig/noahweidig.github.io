/** The children of the <svg>, whitespace collapsed. Sliced rather than matched:
    a regex spanning the whole file backtracks for no benefit here. */
const inner = (svg) => {
  const open = svg.indexOf('>', svg.indexOf('<svg'));
  const close = svg.lastIndexOf('</svg>');
  return svg
    .slice(open + 1, close)
    .replace(/\s+/g, ' ')
    .replaceAll(' />', '/>')
    .trim();
};

/** Material's own attributes, repeated on the wrapper so SVGO sees the same
    context the icon renders in. */
const WRAP = 'xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" fill="#000"';

const slim = (body) =>
  inner(
    optimize(`<svg ${WRAP}>${body}</svg>`, {
      multipass: true,
      floatPrecision: 3,
      plugins: [{ name: 'preset-default', params: { overrides: { cleanupIds: false } } }],
    }).data,
  );

/** Icons the client scripts build as strings (src/scripts/icon.ts). Kept to
    their own small file so the scripts do not bundle the whole set. */
const SCRIPT = ['copy', 'check', 'pilcrow', 'left', 'right', 'close'];

const entries = await Promise.all(
  Object.entries(MAP).map(async ([name, file]) => {
    const svg = await readFile(path.join(iconDir, `${file}.svg`), 'utf8');
    return `  ${JSON.stringify(name)}: { viewBox: "0 -960 960 960", body: ${JSON.stringify(slim(inner(svg)))} },`;
  }),
);

const out = `/* Generated by scripts/generate-icons.mjs — do not edit by hand.
   Material Symbols Sharp (Apache-2.0), 960 grid, optimized with SVGO. */
export const icons: Record<string, { viewBox: string; body: string }> = {
${entries.join('\n')}
};
`;
const scriptEntries = entries.filter((e) =>
  SCRIPT.some((n) => e.startsWith(`  ${JSON.stringify(n)}:`)),
);
const scriptOut = `/* Generated by scripts/generate-icons.mjs — do not edit by hand.
   The subset of icons.generated.ts that client scripts need as strings. */
export const scriptIcons: Record<string, { viewBox: string; body: string }> = {
${scriptEntries.join('\n')}
};
`;
const scriptTarget = new URL('../src/lib/icons.script.generated.ts', import.meta.url);
await writeFile(scriptTarget, scriptOut);
const target = new URL('../src/lib/icons.generated.ts', import.meta.url);
await writeFile(target, out);
// `npm run lint` checks formatting across the tree, so the generated file has
// to come out the way Prettier would write it.
await promisify(execFile)('npx', [
  'prettier',
  '--write',
  fileURLToPath(target),
  fileURLToPath(scriptTarget),
]);
