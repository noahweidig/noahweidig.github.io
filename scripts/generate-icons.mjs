/**
 * Rebuild src/lib/icons.generated.ts from lucide-static.
 *
 * Every non-brand icon on the site comes from Lucide so the whole set shares
 * one grid, one stroke and one set of terminals. Brand marks stay hand-drawn
 * in Icon.astro — Lucide does not ship them.
 *
 *   node scripts/generate-icons.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const iconsDir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');

/** site name -> lucide icon file name */
const MAP = {
  rss: 'rss',
  mail: 'mail',
  message: 'message-square-text',
  calendar: 'calendar-days',
  briefcase: 'briefcase-business',
  school: 'school',
  code: 'code-xml',
  users: 'users',
  sparkles: 'sparkles',
  layers: 'layers',
  trophy: 'trophy',
  bulb: 'lightbulb',
  file: 'file-text',
  pencil: 'pencil',
  help: 'circle-question-mark',
  search: 'search',
  pin: 'map-pin',
  clock: 'clock',
  cube: 'box',
  download: 'download',
  arrow: 'arrow-right',
  external: 'external-link',
  sun: 'sun',
  moon: 'moon',
  menu: 'menu',
  close: 'x',
  satellite: 'satellite',
  chart: 'chart-column',
  ai: 'brain-circuit',
  leaf: 'leaf',
  database: 'database',
  terminal: 'square-terminal',
  quote: 'quote',
  video: 'video',
  news: 'newspaper',
  shield: 'shield-check',
  slides: 'presentation',
  book: 'book-open',
  report: 'clipboard-check',
  preprint: 'file-clock',
  check: 'check',
  tag: 'tag',
  copy: 'copy',
  link: 'link',
  hash: 'hash',
  reader: 'book-open-text',
  expand: 'expand',
  zoom: 'zoom-in',
  left: 'chevron-left',
  right: 'chevron-right',
  printer: 'printer',
  filePdf: 'file-down',
  filter: 'sliders-horizontal',
  info: 'info',
};

const inner = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*\/>/g, '/>')
    .trim();

const entries = [];
for (const [name, file] of Object.entries(MAP)) {
  const svg = await readFile(path.join(iconsDir, `${file}.svg`), 'utf8');
  entries.push(`  ${name}: ${JSON.stringify(inner(svg))},`);
}

const out = `/* Generated by scripts/generate-icons.mjs — do not edit by hand.
   Lucide (ISC, lucide.dev), 24x24 grid, stroke-width 2 as authored. */
export const lucideIcons: Record<string, string> = {
${entries.join('\n')}
};
`;
const target = new URL('../src/lib/icons.generated.ts', import.meta.url);
await writeFile(target, out);
// `npm run lint` checks formatting across the tree, so the generated file has
// to come out the way Prettier would write it.
await promisify(execFile)('npx', ['prettier', '--write', fileURLToPath(target)]);
console.log(`wrote ${entries.length} icons`);
